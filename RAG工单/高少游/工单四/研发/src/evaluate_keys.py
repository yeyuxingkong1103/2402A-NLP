def hit(text: str, tokens: list[str]) -> bool:
    """文本是否命中任一关键线索（去空白与全角逗号后子串匹配）。"""
    if not text:
        return False
    t = text.replace(" ", "").replace("，", ",")
    return any(tok.replace(" ", "") in t for tok in tokens)


def hit_detail(text: str, tokens: list[str]) -> dict:
    """返回命中详情（命中的线索 + 是否命中），供报告逐题展开。"""
    if not text:
        return {"hit": False, "matched": []}
    t = text.replace(" ", "").replace("，", ",")
    matched = [tok for tok in tokens if tok.replace(" ", "") in t]
    return {"hit": bool(matched), "matched": matched}