HEAD_FIELDS = {  # 表头行上方单独列出的抬头项（不属于表格主体）
 "现存生物": ["调查单位","调查负责人","调查时间"],
}


def build():
    """按 MAP 为三份标准的附录 A 表格逐一生成知识卡。

    返回：list[dict]，一张表一张卡。卡内 record_form 保存表号、表名、
    表头抬头项、列定义与表注；vision 通道的卡置 needs_human_review=True，
    并在 ocr_uncertain 记录「旋转 90° 横向排版、经视觉通道转录」的提示。
    """
    cards = []
    for crop, rows in MAP.items():          # 逐作物处理
        std_no, std_name = STD[crop]
        for no, page, name, fkey, note, chan in rows:  # 逐表：表号/PDF页/表名/字段集/表注/数据通道
            cols = F[fkey]                  # 该表的列字段清单
            head = HEAD_FIELDS.get(fkey, []) + GROUP_ROW.get(fkey, [])  # 表头抬头项 + 跨整行分组表头
            cards.append({
                # card_id：{标准号去斜杠空格}-p{PDF页}-a{表号两位}，全局唯一
                "card_id": f"{STD_ID[crop]}-p{page}-a{no:02d}",
                "std_no": std_no, "std_name": std_name, "authority_level": 1, "year": 2011,
                "region": "全国", "crop": crop, "crop_alias": [],
                "growth_stage": None,
                "knowledge_type": "档案记录",
                "type_group": "其他",
                "pest_kind": None,
                "subtype": name,
                "title": f"{crop}{name}（附录A 表A.{no}）",
                "symptoms": None,
                "trigger": None,
                "record_form": {"table_no": f"表A.{no}", "table_name": name,
                                "header_items": head, "columns": cols,
                                "footnote": note, "is_blank_form": True},
                "measures": [], "chemicals": [],
                "fertilizer": None,
                "precautions": None,
                "is_high_risk": False,
                "high_risk_reasons": [],
                "needs_human_review": chan == "vision",  # 视觉通道转录的卡需人工复核
                "needs_verification_hint": False,
                "source": {"std_no": std_no, "section": f"附录A 表A.{no}", "page": page,
                           "channel": chan, "quote": f"表A.{no} {name}"},
                "ocr_uncertain": (["表格为旋转 90° 的横向排版，经视觉通道转录"]
                                  if chan == "vision" else []),
                "missing_fields": [],
                "in_scope": False,
            })
    return cards


if __name__ == "__main__":
    # 生成全部附录 A 知识卡并写出 JSONL（一行一卡）
    cards = build()
    dst = os.path.join("data", "processed", "appendixA_cards.jsonl")  # 输出文件路径
    with open(dst, "w", encoding="utf-8") as f:
        for c in cards:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")  # 每行写一个 JSON 卡片
    print(f"{dst}: {len(cards)} 张卡")
    # 按作物统计卡数，并单独统计走视觉通道（需人工复核）的数量
    for crop in MAP:
        n = sum(1 for c in cards if c["crop"] == crop)
        v = sum(1 for c in cards if c["crop"] == crop and c["source"]["channel"] == "vision")
        print(f"  {crop}: {n} 张（vision {v}）")
