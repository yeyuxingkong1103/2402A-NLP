"""数据访问层统一导出。

本模块把三个存储的入口集中暴露，让上层可以写出对称、易读的调用代码：
    from src.db import mysql, redis, milvus
而不是记忆各自的真实路径（mysql/redis/milvus 分别位于 src/db/ 下）。

三个存储的分工：
- mysql  : 关系型主库，存用户、角色、会话、消息、文档元数据等强一致数据；
- redis  : 缓存与短期记忆，存最近若干轮对话、限流计数、分布式锁、JWT 黑名单；
- milvus : 向量库，存知识库分块向量与长期记忆摘要向量，负责语义检索。

这里只做“导入转发”，不创建任何连接。原因：导入本模块通常发生在应用启动早期，
此时配置/网络可能尚未就绪；把连接创建推迟到各自模块的 get_xxx() 懒加载函数里，
可以保证导入永远不会因为外部服务不可用而失败（可用性优先）。
"""

# 只导入子模块本身（而不是里面的函数），保持命名空间清晰：
# 调用方一眼就能看出数据来自哪种存储，如 mysql.get_db()、redis.get_redis()。
from src.db import milvus, mysql, redis

# 显式声明公开导出项：一是让 IDE / 类型检查器知道这三个名字是稳定 API，
# 二是防止 `from src.db import *` 时把无关的内部变量也带出去。
__all__ = ["mysql", "redis", "milvus"]