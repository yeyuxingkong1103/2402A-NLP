            role, kind = ev["role"], ev["kind"]
            verified, detail = False, ""
            if kind in ("verbatim", "diagram_text_layer"):
                needle = normalize(ev["text"])
                verified = needle in pt
                detail = f"逐字串长度 {len(needle)}"
                if not verified:
                    problems.append(f"id {rid}: 页 {p} 未逐字包含证据：{ev['text'][:60]}…")
