# 问价意图词表是「该给费用区块」的第二路判据（命中则不看回答状态）。
#
# 为什么正反例都要写满：这张表的两个失败方向代价不对称 —— 误判（把不问价的问句
# 当问价）只是公众侧多一块费用信息与一次 DeepSeek 调用；漏判（用户问价却没命中）
# 会让用户什么都拿不到，那正是本批存在的理由。故每个词都配一条它会命中的问句
# （防止规则被后来者改成死规则），并单独钉住「问法律但不问价」的反例。
