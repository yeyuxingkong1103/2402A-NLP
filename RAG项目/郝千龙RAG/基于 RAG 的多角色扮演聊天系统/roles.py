def get_role(code: str) -> dict:  # 按 code 查角色模板；命中返回完整字典，未命中回退默认教师角色，保证调用方总有可用角色
    """按 code 取角色模板；未命中回退默认教师角色。"""  # 函数文档字符串，说明回退策略
    return ROLES.get(code) or ROLES["teacher"]  # dict.get 命中返回该角色；返回 None 时 or 短路回退 "teacher"，避免 KeyError


def list_roles() -> list[dict]:  # 对外暴露角色列表，剔除 system_prompt 防止提示词泄露给前端
    """对外角色列表（剔除 system_prompt，避免提示词泄露给前端）。"""  # 函数文档字符串，说明剔除原因
    return [  # 用列表推导式生成对外角色列表
        {k: v for k, v in item.items() if k != "system_prompt"}  # 字典推导式：复制除 system_prompt 外的所有字段，避免提示词泄露
        for item in ROLES.values()  # 遍历 ROLES 全部角色配置
    ]


