def path_of(doc):
    return CORPUS_DIR / doc["file"]


def available():
    """返回实际存在的文档（缺文件的跳过，便于在别的机器上复现）。"""
    return [{**d, "path": path_of(d)} for d in DOCS if path_of(d).exists()]


