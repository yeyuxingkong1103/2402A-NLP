"""角色预设：每个人物角色 = 头像 + 提示词模板 + 专属知识库。

内置两个角色：心理咨询师、律师。两者的知识库都来自公开数据集（见
scripts/fetch_datasets.py），按 role_id 隔离召回。

`avatar` 用单个 emoji 表示角色身份，前端直接渲染在头像位置上（详见 app/static/index.html）。
挑一个能一眼认出职业的表情即可，例如心理咨询师 🧠、律师 ⚖️。
"""
from __future__ import annotations

# ---- 这张表的键结构契约 ----
# 三个调用方都按同一套键取值（main.py 启动时批量登记、pipeline.ensure_role 首次访问时
# 登记、scripts/seed.py 灌知识库），缺键不会静默降级，直接 KeyError：
#   role_id（字典的键本身）  必填。它会被写进 roles.id，同时作为 Milvus 里每个 chunk 的
#                           role_id 过滤字段（检索只在本角色自己的知识库里搜），前端还拿它
#                           当 localStorage 里的会话分组键。所以它是一份**持久标识**：
#                           改个名字等于换了一个角色，老 id 上的知识库和历史会话都不会跟过来。
#                           字符集也受限，见 schemas.ROLE_ID_PATTERN（id 会被拼进 Milvus 过滤
#                           表达式，引号之类的字符能改写表达式，必须在入口就挡掉）。
#   name                    必填。展示名，前端角色下拉框与消息气泡上的「谁在说话」用它。
#   avatar                  可省略（取值处一律 preset.get("avatar", "")）。单个 emoji。
#                           前端把它当**纯文本**渲染：esc() 转义后直接写进头像圆框
#                           （app/static/index.html 的 addMsgView），所以只能放一个字符宽的
#                           表情，不能放 URL / 图片 / 多个表情；也不要用 HTML。
#                           注意「单个 emoji」不等于单个码点：⚖️ 就是「表情 + 变体选择符」
#                           两个码点。库里那一列是 String(16)、接口侧限 max_length=16，就是给
#                           这种差着几倍长度的写法留的余量。
#   description             必填。一句话职责说明，只在 /role/list、/role/{id} 里回给前端做展示，
#                           不参与提示词。
#   system_prompt           必填。人设本体。拼提示词时它排在 system 消息的**最前面**，检索资料
#                           与通用的「作答要求」都追加在它之后（见 templates.build_messages）。
#                           第一行是职业身份、第二行是语气，第 3 条起是各角色自己的免责/边界口径
#                           ——这是角色私有的东西，模板层注入不了。
#
# 新增一个角色要动的地方：
#   1) 在下面这张表里加一条（键 = role_id），这是唯一的必做项；
#   2) 给这个 role_id 备知识库并入库，否则它一上来就是零召回——templates.py 里
#      「本次没有检索到任何知识库资料」那个分支就是为这种情况准备的（能聊、但不出具体事实）；
#   3) 走 scripts/seed.py 灌数据的话，还要在它的 SEED_KNOWLEDGE 里加上该 role_id 对应的语料目录，
#      否则 seed 只打一条「跳过未知角色」的 warning 就跳过；
#   4) /role/list、/chat、前端都不用改：角色是数据驱动的，main.py 启动时按本表逐个
#      ensure_role() 登记。运行时新增角色也可以直接 POST /role，不必改本文件。
#   顺序：本表的书写顺序决定 main.py 的注册顺序（全新库里的插入顺序），但 /role/list 走的
#   sql.list_roles() 没有 order_by，实际返回顺序由数据库决定，别把这里的前后关系当前端
#   下拉框顺序的保证。
#
# 为什么两个角色的 system_prompt 里都重复写了同一套「只依据知识库资料作答 / 没资料就
# 明说 / 专业风险提示」——这是刻意重复，不是复制粘贴留下的冗余：
#   * 通用作答要求那段是 templates.build_messages 在**有/无检索结果**两种情况下分别追加的，
#     与角色无关；但各角色的职业口吻与免责口径（律师要说「不构成正式法律意见」、心理咨询师
#     要处理自伤危机）是角色私有的，模板里没有、也不该有。
#   * 所以新角色照现有条目的结构抄（职责 → 语气 → 4 条回答规则）即可；模板里那段通用要求
#     是各角色共用的兜底，删掉某个角色的前两条也不会报错，只是这个角色的答案会退化到
#     「只有职业口吻、没有事实纪律」。
