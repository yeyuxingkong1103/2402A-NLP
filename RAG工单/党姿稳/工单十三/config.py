# ---------------------------------------------------------------------------
# 零、进程级环境变量（必须在 torch 被导入前设置，故放在本模块最顶部）
# ---------------------------------------------------------------------------
# OMP_WAIT_POLICY=PASSIVE：OpenMP 线程空闲时转入休眠而非自旋等待。
# 本机内存吃紧（16GB 主机、WSL 分配约 7.8GB），默认的自旋等待会让被抢占的
# 工作线程持续空转，实测单个查询的编码耗时因此在 0.2~14 秒间剧烈抖动；
# 改为 PASSIVE 后抖动显著收敛。
os.environ.setdefault("OMP_WAIT_POLICY", "PASSIVE")             # OpenMP 线程空闲休眠
# 关闭 tokenizers 的多进程并行，避免与 torch 线程池二次争抢 CPU
os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")        # 禁用分词并行

# Windows 控制台默认 GBK，打印中文日志或百分号符号时会抛 UnicodeEncodeError
# 这里统一把标准输出与错误流切换为 UTF-8，保证程序不因编码问题中断
for _name in ("stdout", "stderr"):                              # 依次处理标准输出与标准错误
    _stream = getattr(sys, _name, None)                         # 取出对应流对象
    if _stream is not None and hasattr(_stream, "reconfigure"):  # 流支持重新配置时才处理
        try:                                                    # 尝试重配置
            _stream.reconfigure(encoding="utf-8", errors="replace")  # 改为 UTF-8 并替换不可编码字符
        except Exception:                                       # 被重定向等场景可能失败
            pass                                                # 忽略失败，不影响主逻辑

