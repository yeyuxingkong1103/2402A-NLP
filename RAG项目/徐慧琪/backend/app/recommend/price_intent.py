"""问价意图：问句是不是在问「请律师要花多少钱」。

存在的理由（用户 2026-09-29 第二次裁决，第四批）：费用区块的接入判据从
「公众侧 + 状态 ≠ out_of_scope」再放缓一步，变成「公众侧 +（状态 ≠ out_of_scope
**或** 问句命中问价意图）」。第二路是**实测逼出来的**：模型把「律师费大概多少」
判成 out_of_scope（原话「这属于律师服务收费的**市场行情**问题，不是由上面这些
法条来规定的内容」），也就是这个状态在本链路上更像「**这些法条答不了**」，而不是
「与法律无关」—— 而用户问价时恰恰最容易落进这一档（2/2 复现）。于是裁决举的那个
例子在上一版判据下仍然什么都拿不到，本模块就是为它开的第二路。

为什么是词表而不是放宽状态（本批要回答的那个「为什么」）：放宽状态只有两条路可走 ——
① 连模型自报的 out_of_scope 一起放行，则「今天天气怎么样」也会带出费用区块
（用户明确点名它**不该**出现，费用侧还会拿近零分命中白跑一次 DeepSeek）；
② 只排除 boundaries.is_refusal 那条规则出口，则「胜诉概率」这类真拒答会带出区块 ——
那正是「系统在回应我这件事」的观感，且同样拦不住天气题（它是模型自报的）。
词表是唯一同时满足「用户问价必给」与「天气题不给」两端的做法，代价是它只能靠
穷举测试保证边界。

为什么是纯规则而不是模型（与 cause.py 同一口径）：可穷举测试、可解释、零成本，
而多一次模型判定就是每问一次多一次调用与一次判错的可能。误判的代价写在下文
每条规则注释里 —— 都要能落到「多花一次费用检索 + 一次 DeepSeek 调用」这个
已知并接受的额度内，**不能**落到「把与法律无关的问题答成在回应它」。
"""
from __future__ import annotations

import re

# 问价规则。顺序不参与语义（任一命中即算），但每条都写清了它的误判面：
# 命中面放宽的代价是钱（一次检索 + 一次生成），收紧的代价是用户问价拿不到东西，
# 所以贴着「这笔钱」的语义写，不贴「疑问」这种形式。
PRICE_INTENT_RULES: list[re.Pattern[str]] = [
    # ① 直问数额：「多少钱」「几块钱」。刻意不留裸「多少」——「押金多少」
    #   「租金多少」「要多少年」问的是法律事实本身的量，不是问价，命中它们
    #   等于在租赁/劳动问句上白花一次费用检索与一次 DeepSeek 调用。
    #   「多钱」是「多少钱」的口语省写，单独列；它又会命中「很多钱」，
    #   而「打官司要花很多钱吗」确实是在问价，故不算误判。
    re.compile(r"多少钱|多钱|几块钱|多少块"),
    # ② 收费概念词。**不能用裸「费」**：「浪费」「免费」「消费」都会命中，
    #   而它们恰恰长在正经法律问句里（消费者权益、物业纠纷）——「免费的法律
    #   援助怎么申请」是真法律问句，裸「费」会把它当问价。多字词无此歧义。
    #   「成本/预算/开销/花销」是终审复核补的：它们是**同一诉求的另一种说法**
    #   （「打官司的成本高吗」「诉讼的开销大概多少」），实测 6 条真实问价说法
    #   因缺它们而漏判，恰是用户原始诉求那一侧。误判面：「违约成本」这类法律
    #   事实问句会命中 —— 代价是多一次费用检索与一次生成，方向仍是可接受的那一侧。
    re.compile(r"费用|收费|计费|费率|成本|预算|开销|花销"),
    # ③ 具体费名。这些词本身就限定了「某项服务的钱」，不存在第二种语义；
    #   它们大多含「费」却比裸「费」长，故与②并列而不合并。
    re.compile(r"律师费|诉讼费|代理费|服务费|咨询费|受理费|公证费|辩护费"),
    # ④ 价格名词。已知误判面：「价格欺诈」「明码标价」是消费者在问法律怎么办，
    #   不是在问价。用户裁决点名要覆盖「报价」「价格」，故保留 —— 误判的代价
    #   只是多一块信息与一次费用调用，区块里的数字仍要过 fees 的数值回查，
    #   编不出来（与「与法律无关却给区块」不是一类问题）。
    re.compile(r"报价|价格|价钱|价位|标价|单价|要价"),
    # ⑤ 问贵贱。「贵」必须带疑问尾字而不是裸词：「贵重物品」「物价贵」是陈述
    #   或法律事实，裸「贵」会连它们一起网进来。划不划算/合不合算同属问价。
    re.compile(r"贵(不|吗|么)|划不划算|合不合算"),
    # ⑥ 动宾式带量词：「收多少钱」「要几万」「花几千」「怎么收钱」。①②③④⑤都覆盖
    #   不到这种口语形态。限定为「收|要|花|付|掏 + 多少/几 + 量词」，不认裸「收」「要」——
    #   「公司收了我的押金合法吗」是法律问句，裸词会误判。末尾的 `(收|花)钱` 是终审
    #   复核补的省写形态（「这个案子律师怎么收钱」）—— 它必须是「收/花 + 钱」整体，
    #   「退钱」「赔钱」不在其中（那是请求返还或赔偿，不是问价）。
    re.compile(r"(收|要|花|付|掏)(多少|几)(钱|块|万|千)|(收|花)钱"),
    # ⑦ 动宾式不带量词：「律师收多少」。只认 收|花|付|掏，**刻意不含「要」**——
    #   「要多少年」「要多少人」「要多少证据」是时长/人数/份数问句，在离婚、
    #   诉讼时效这类法律问句里密度极高，是这张表最容易误伤的邻居；而「要多少」
    #   若真在问钱，多数会写成「要多少钱」（已被①②⑥接住）。
    re.compile(r"(收|花|付|掏)多少"),
]


# 法律服务语境词（用户 2026-09-29 第三次裁决：问价意图须**同时**命中语境）。
#
# 为什么必须再收这一层：问价词表本身只能保证「**不含**问价词的非法律题不给」，
# 管不住「**含**问价词的非法律题」—— 终审复核自造 10 条非法律问价题实测 8 条命中
# （「今天油价多少钱」「iPhone 15 多少钱」「白菜多少钱一斤」…），它们会拿到律师卡片
# 与费用区间，与上一句「这不属于法律问题」当面矛盾，还白花一次付费调用。
#
# 代价（已知并接受，用户裁决）：省略语境的问法会漏判（「你们收费怎么算」「先给我个报价」
# 不含任何语境词）。方向是「不给」而不是「给错」—— 与词表其余部分同一取舍。
# 词表刻意写宽（含「案子」这种口语形）：收紧方向才是错的代价那一侧。
#
# **一条 pattern 一个词族**（不是一条大交替式）：本项目的结构用例按 `PRICE_INTENT_RULES`
# 的形态写成「逐条规则至少被一条正例命中」；写成单条大交替式时那个循环只跑一次，
# 断言退化成「总有正例含某个语境词」，**八个词删掉也不会变红**（第四批复审核实）。
# 拆开后每个词族都要有正例撑着，孤儿词会当场暴露。
#
# 两处**收紧**（复核实测的残存误伤，2026-09-29）：裸「法律」是万能前缀
# （「法律规定打车多少钱一公里」照样命中），裸「代理」会网住「代理记账」「淘宝代理」——
# 二者都只认与服务/纠纷相关的复合形。代价是新增少量漏判（「办个法律服务多少钱」若
# 不写成「法律咨询」会掉），方向仍是「不给」而非「给错」。
LEGAL_CONTEXT_RULES: list[re.Pattern[str]] = [
    re.compile(r"律师"),
    re.compile(r"官司"),
    re.compile(r"诉讼"),
    re.compile(r"起诉"),
    re.compile(r"案件|案子"),
    re.compile(r"纠纷"),
    re.compile(r"法院"),
    re.compile(r"辩护"),
    re.compile(r"仲裁"),
    # 裸「代理」→ 只认与法律服务相关的复合形。
    # lookbehind 挡的是「商标/专利代理**费用**」这类：`代理费` 是「代理费用」的子串，
    # 不收就会被「商标代理费用多少」命中（复核实测的漏网）。六个前缀都是等长二字，
    # 满足 Python 定长 lookbehind 的要求
    re.compile(r"(?<!商标|专利|工商|税务|记账|报关)代理费|代理案件|诉讼代理"),
    # 裸「法律」→ 只认服务类复合形（「法律规定 X 多少钱」是万能前缀，不是语境）
    re.compile(r"法律问题|法律服务|法律咨询"),
    # 法律服务名的**客体词**（复核指出的整族漏判 ——「代写一份合同多少钱」这类
    # 只是省掉了「律师」二字）。
    # **只认客体，不认动词**：初版收了 `代写|起草|审查|见证|文书`，被复核实测
    # 10/10 误伤 —— 泛用动词能挂任何客体（代写作业、起草简历、见证取样、资格审查），
    # 等于把用户两次裁决要关的「非法律问价题」用新形态放了回来。客体词一旦出现
    # 几乎必然是法律服务，且经复核模拟验证：换成客体词后 28/28 正例全保留
    re.compile(r"合同|协议|遗嘱|诉状|起诉状|法律文书|律师函|答辩状"),
    re.compile(r"赔偿"),
]


def is_price_intent(question: str) -> bool:
    """问句是否在问「请律师要花多少钱」—— 问价词与法律服务语境**两者都要**。

    只问价不看语境，会把「今天油价多少钱」也当成费用区块的通行证；只看语境不问价，
    则任何法律问句都会带出费用。认不出返回 False（不猜，与 cause.tag 同口径）。

    返回 bool 而不是标签：下游只用它做一次「要不要组装费用区块」的分支，
    多给一层语义（如「问的是总额还是单价」）当前没有消费方，加了就是死代码。
    """
    text = question or ""
    if not any(pattern.search(text) for pattern in PRICE_INTENT_RULES):
        return False
    return any(pattern.search(text) for pattern in LEGAL_CONTEXT_RULES)
