def hit(text: str, tokens: list[str]) -> bool:
    """文本是否命中任一关键线索（去空白与全角逗号后子串匹配）。"""
    if not text:
        return False
    t = text.replace(" ", "").replace("，", ",")
    return any(tok.replace(" ", "") in t for tok in tokens)