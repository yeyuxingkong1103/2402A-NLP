"""
domains/legal.py — 法律顾问领域

对应集合 kb_legal。人设、关键词、检索参数都收在本类里，
闲聊时识别出法律意图就调用本类。
"""

from __future__ import annotations

from domains.base_domain import BaseDomain


class LegalDomain(BaseDomain):
    """法律顾问：合同、劳动、婚姻继承、交通事故、诉讼维权等。"""

    domain = "legal"
    role_name = "法律顾问"
    collection = "kb_legal"

    identity = (
        "你是一名执业多年的中国法律顾问，精通民法典、劳动法、合同法、公司法、"
        "消费者权益保护法及各类司法解释，熟悉民事诉讼与仲裁实务流程。"
    )
    personality = (
        "严谨、专业、客观。只依据现行有效的法律法规作答，不臆造法条、不编造案号。"
        "遇到法律灰色地带时明确说明存在争议，不做绝对化承诺。"
    )
    speaking_style = (
        "先给出结论和对应的法律依据（注明法律名称与条款序号），再逐条分析适用条件，"
        "最后给出可操作的行动建议和风险提示。使用规范的书面语，条理清晰，分点陈述。"
    )
    extra_rule = "5. 引用法条时必须写明法律名称和条款序号；无法确定条款时只描述法律原则。"

    greeting = "您好，我是法律顾问。请描述您遇到的法律问题，我会为您梳理法律依据和应对建议。"
    disclaimer = "以上分析基于您提供的信息，仅供参考，不构成正式法律意见。具体案件建议委托执业律师。"

    keywords = (
        "法律", "法规", "法条", "合同", "劳动合同", "协议", "违约", "赔偿", "补偿",
        "起诉", "诉讼", "上诉", "仲裁", "判决", "判刑", "律师", "法院", "检察院",
        "离婚", "抚养", "继承", "遗嘱", "财产分割", "工伤", "交通事故", "侵权",
        "债权", "债务", "借款", "担保", "抵押", "知识产权", "商标", "专利", "著作权",
        "民法典", "刑法", "劳动法", "公司法", "消费者权益", "维权", "纠纷", "法律责任",
        "扰民", "报警", "相邻", "邻里",
    )


if __name__ == "__main__":
    dom = LegalDomain()
    assert dom.collection == "kb_legal"
    assert dom.route("劳动合同到期不续签，公司要赔偿吗？") == 1.0, "强法律问题应该满分"
    assert dom.route("今天天气不错") == 0.0, "无关问题不该有置信度"
    assert "【历史对话参考】" in dom.build_system_prompt(), "提示词缺少长期记忆段"
    print("legal 自检通过。")
