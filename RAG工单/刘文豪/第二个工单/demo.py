# -*- coding: utf-8 -*-
"""
工单编号：人工智能 NLP-RAG-基于 PDF 文档的问答系统优化
演示：同一问题列表上对比 工单01基线 与 本工单优化版 的回答
运行：python demo.py
"""
import time
from pathlib import Path

import rag

# 工单01/02 要求的检索问题列表（《招股说明书1》：武汉兴图新科电子股份有限公司）
QUESTIONS = [
    ("260", "报告期内，武汉兴图新科电子股份有限公司来自军用领域的收入分别是多少？"),
    ("95", "武汉兴图新科电子股份有限公司参与制定了哪个技术标准？"),
    ("33", "报告期内，武汉兴图新科电子股份有限公司来自军用领域的收入占主营业务收入的比重分别是多少？"),
    ("34", "根据武汉兴图新科电子股份有限公司招股意向书，电子信息行业的上游涉及哪些企业？"),
    ("957", "武汉兴图新科电子股份有限公司在哪个领域已经成为重要供应商？"),
    ("793", "根据武汉兴图新科电子股份有限公司招股意向书，电子信息行业的下游主要包括哪些行业？"),
    ("795", "武汉兴图新科电子股份有限公司参与的哪个工程荣获了国家科技进步一等奖？"),
    ("543", "武汉兴图新科电子股份有限公司注册资本是多少？"),
    ("531", "武汉兴图新科电子股份有限公司法定代表人是谁？"),
]

# 工单01基线运行结果（摘自 ../第一个工单/演示结果.md）
BASELINE = {
    "260": "未找到（表格被切碎，检索到相关段落但无完整数字）",
    "95": "未找到（标准名称句被窗口截断）",
    "33": "部分正确（2018年94.84%、2017年97%…，缺2016）",
    "34": "正确（上游：电子元器件制造企业、机箱机柜等金属壳体制造企业）",
    "957": "正确（国防军队视频指挥领域）",
    "793": "未找到（检索命中但模型以'不够全面'拒答）",
    "795": "正确（视频指挥分系统工程）",
    "543": "正确（5,520.00 万元）",
    "531": "正确（程家明）",
}


def main():
    col = rag.get_collection()
    lines = ["# 工单02 演示结果：检索优化前后对比", "",
             "优化点：①段落/表格感知分块 ②提示词强制直答 ③top_k=6+低分过滤", ""]
    ok = 0
    for qid, q in QUESTIONS:
        t0 = time.time()
        ans, hits = rag.answer(col, q)
        dt = time.time() - t0
        pages = ", ".join(str(h["page"]) for h in hits[:3])
        print(f"[{qid}] {dt:.1f}s  {q}\n  -> {ans[:100]}\n")
        lines += [f"## id={qid}", f"**Q**：{q}", "",
                  f"- 工单01基线：{BASELINE[qid]}",
                  f"- 工单02优化：{ans}",
                  f"- 耗时 {dt:.1f}s；引用页码：{pages}", ""]
        if "未找到" not in ans:
            ok += 1
    acc = ok / len(QUESTIONS) * 100
    lines += ["## 汇总", f"- 直接给出答案：{ok}/{len(QUESTIONS)}（{acc:.0f}%）",
              "- 验收标准：准确率 90% 以上 → " + ("达标" if acc >= 90 else "未达标，见 README 分析")]
    Path("演示结果.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"命中率 {ok}/{len(QUESTIONS)}，已保存 -> 演示结果.md")


if __name__ == "__main__":
    main()
