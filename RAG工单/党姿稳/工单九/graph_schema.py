# 工单编号：人工智能NLP-RAG-Graph RAG 优化任务
# 模块职责：定义金融领域实体/关系类型体系与两版抽取提示词（优化前基线 / 优化后 schema 约束）
# 优化要点：这是工单九『prompt 构建实体、关系』层面的优化落点

# ---------------------------------------------------------------------------
# 一、优化后的实体类型体系（金融领域强约束，避免自由抽取导致的类型混乱）
# ---------------------------------------------------------------------------
ENTITY_TYPES = {                                                # 实体类型定义：类型名 -> 中文说明
    "ORG": "机构：银行、保险公司、证券公司、上市公司、子公司、监管机构",  # 组织机构类实体
    "PERSON": "人物：董事长、行长、董事、监事、高管等自然人",        # 人物类实体
    "BUSINESS": "业务/产品：零售业务、对公业务、信用卡、理财产品、保险产品",  # 业务与产品类实体
    "METRIC": "财务指标：营业收入、净利润、拨备覆盖率、不良贷款率、资本充足率",  # 财务指标类实体
    "VALUE": "数值：金额、百分比、比例、股数等量化取值",             # 数值类实体
    "TIME": "时间：年份、季度、报告期、具体日期",                    # 时间类实体
    "REGION": "地区：省、市、国家、区域",                           # 地理区域类实体
    "RISK": "风险：信用风险、市场风险、流动性风险、操作风险",         # 风险类实体
    "REGULATION": "法规政策：监管规定、会计准则、行业政策",          # 法规政策类实体
    "EVENT": "事件：发行、上市、并购、重组、获奖、合作等事件",        # 事件类实体
}

# ---------------------------------------------------------------------------
# 二、优化后的关系类型体系（限定关系名，保证图谱可查询、可聚合）
# ---------------------------------------------------------------------------
RELATION_TYPES = {                                              # 关系类型定义：关系名 -> 中文说明
    "EMPLOYED_BY": "任职于：人物 -> 机构",                       # 人物与机构的任职关系
    "HOLDS": "持股：机构/人物 -> 被持股机构（可带比例）",          # 股权持有关系
    "SUBSIDIARY_OF": "子公司：子公司 -> 母公司",                  # 母子公司关系
    "INVESTS_IN": "投资：机构 -> 被投资项目/机构",                # 投资关系
    "ISSUES": "发行：机构 -> 发行的股票/债券/产品",               # 发行关系
    "DISCLOSES": "披露：机构 -> 披露的报告/信息",                 # 信息披露关系
    "HAS_METRIC": "指标取值：机构 -> 财务指标",                   # 机构与其指标的关联
    "METRIC_VALUE": "指标数值：财务指标 -> 数值",                 # 指标与具体数值的关联
    "OCCURS_IN": "发生于：事件 -> 时间",                         # 事件与时间关系
    "LOCATED_IN": "位于：机构/事件 -> 地区",                      # 地理归属关系
    "COOPERATES_WITH": "合作：机构 -> 机构",                      # 合作关系
    "REGULATED_BY": "受监管于：机构 -> 监管机构/法规",             # 监管关系
    "AFFECTS": "影响：风险/事件 -> 机构/指标",                    # 影响关系
}

# 输出 JSON 的结构约束说明（供提示词拼装）
_OUTPUT_SCHEMA = """{"entities": [{"name": "实体名称", "type": "类型名"}], \
"relations": [{"head": "头实体名称", "head_type": "类型名", "relation": "关系名", \
"tail": "尾实体名称", "tail_type": "类型名", "evidence": "支撑该关系的原文短句"}]}"""


def _type_lines(mapping):                                       # 定义类型清单渲染函数
    """把类型字典渲染成提示词中的编号清单文本。"""
    return "\n".join("%d. %s —— %s" % (i + 1, k, v)             # 逐行拼接『序号. 类型名 —— 说明』
                     for i, (k, v) in enumerate(mapping.items()))  # 遍历类型字典


# ---------------------------------------------------------------------------
# 三、优化前基线提示词：不做类型约束、不要求 JSON、不做归一化
# ---------------------------------------------------------------------------
_BASELINE_SYSTEM = "你是一个信息抽取助手，请从文本中找出实体和它们之间的关系。"  # 宽泛的系统提示（无 schema）

_BASELINE_USER = """请阅读下面的文本，抽取其中的实体和关系。

文本：
%s
"""                                                             # 基线用户提示：仅一句话要求，无条件约束


def baseline_prompt(text):                                      # 定义基线提示词构建函数
    """返回优化前的 (system, user) 提示词二元组。"""
    return _BASELINE_SYSTEM, _BASELINE_USER % text              # 直接填充文本，无任何结构与类型约束


# ---------------------------------------------------------------------------
# 四、优化后提示词：类型体系 + 少量示例 + 严格 JSON 结构 + 归一化要求
# ---------------------------------------------------------------------------
_FEW_SHOT = """示例输入：
平安银行2019年实现营业收入1379.58亿元，不良贷款率为1.65%。

示例输出：
{"entities": [{"name": "平安银行", "type": "ORG"}, {"name": "2019年", "type": "TIME"}, \
{"name": "营业收入", "type": "METRIC"}, {"name": "1379.58亿元", "type": "VALUE"}, \
{"name": "不良贷款率", "type": "METRIC"}, {"name": "1.65%", "type": "VALUE"}], \
"relations": [{"head": "平安银行", "head_type": "ORG", "relation": "HAS_METRIC", \
"tail": "营业收入", "tail_type": "METRIC", "evidence": "平安银行2019年实现营业收入1379.58亿元"}, \
{"head": "营业收入", "head_type": "METRIC", "relation": "METRIC_VALUE", \
"tail": "1379.58亿元", "tail_type": "VALUE", "evidence": "实现营业收入1379.58亿元"}, \
{"head": "平安银行", "head_type": "ORG", "relation": "HAS_METRIC", \
"tail": "不良贷款率", "tail_type": "METRIC", "evidence": "不良贷款率为1.65%"}]}"""  # 少样本示例

_OPT_SYSTEM = """你是金融文本知识图谱抽取专家。你的任务是从金融年报、招股说明书等文本中，\
按照给定的实体类型和关系类型，抽取结构化知识。

严格要求：
1. 实体类型只能从下列类型中选择，不得自造类型：
%s

2. 关系类型只能从下列类型中选择，不得自造关系名：
%s

3. 实体名称必须做归一化：去掉修饰性前缀（如"本行"统一为具体银行名）、\
统一全半角与标点、同一实物的不同写法只保留一个最规范写法。
4. 只抽取原文明确支持的内容，不得推断；每条关系必须给出原文短句作为 evidence。
5. 若文本中没有可抽取的实体关系，返回空数组。
6. 输出必须是合法 JSON，且完全符合下面的结构：
%s"""                                                           # 优化后系统提示（含类型约束）


def optimized_prompt(text):                                     # 定义优化后提示词构建函数
    """返回优化后的 (system, user) 提示词二元组。"""
    system = _OPT_SYSTEM % (_type_lines(ENTITY_TYPES),          # 注入实体类型清单
                            _type_lines(RELATION_TYPES),        # 注入关系类型清单
                            _OUTPUT_SCHEMA)                     # 注入 JSON 结构约束
    user = "%s\n\n现在请抽取下面文本中的实体与关系：\n%s" % (_FEW_SHOT, text)  # 拼装少样本与待抽文本
    return system, user                                         # 返回提示词二元组
