# 案由映射是下游「律师领域」与「费用检索」的共同输入，判错会把用户导向
# 错误的领域。规则表可穷举，所以正例与负例都要写满 —— 尤其要压
# 「同一句里出现两类的词」时的优先序（顺序即语义）。
import pytest

from app.recommend.cause import (
    CAUSE_RULES, CAUSE_TO_FIELD, GENERIC_FIELD, field_of, tag,
)


@pytest.mark.parametrize("question,expected", [
    ("租房押金不退怎么办", "房屋租赁合同纠纷"),
    ("房东要涨租金合理吗", "房屋租赁合同纠纷"),
    ("网购到假货可以要求三倍赔偿吗", "消费者权益纠纷"),
    ("被拖欠工资半年了怎么办", "劳动争议"),
    ("借钱不还没有借条能起诉吗", "民间借贷纠纷"),
    ("离婚后孩子抚养费怎么算", "婚姻家庭纠纷"),
])
def test_tags_the_expected_cause(question, expected):
    assert tag(question) == expected


@pytest.mark.parametrize("question", [
    "今天天气怎么样",
    "我想了解一下民法典的结构",
    "",
])
def test_returns_none_when_no_rule_matches(question):
    """认不出就不猜 —— 下游据此退回「通用」，而不是随便给一个案由。"""
    assert tag(question) is None


def test_specific_rule_wins_over_general():
    """「离婚后房东不退押金怎么办」真正同时命中两条规则：婚姻家庭（离婚）
    与租赁（房东/押金）。规则表顺序即语义：婚姻家庭必须排在租赁之前，
    否则这句会被判成房屋租赁 —— 用例的全部意义就是压住这个顺序。"""
    assert tag("离婚后房东不退押金怎么办") == "婚姻家庭纠纷"


@pytest.mark.parametrize("cause,expected", [
    ("房屋租赁合同纠纷", "房产与建设工程"),
    ("劳动争议", "劳动法"),
    ("消费者权益纠纷", "消费者权益"),
    ("民间借贷纠纷", "金融与借贷"),
    ("婚姻家庭纠纷", "婚姻家庭"),
])
def test_maps_cause_to_field(cause, expected):
    assert field_of(cause) == expected


def test_unknown_or_missing_cause_gives_generic():
    assert field_of(None) == GENERIC_FIELD
    assert field_of("不存在的案由") == GENERIC_FIELD


def test_every_rule_cause_has_a_field():
    """规则表与映射表必须同步：漏一个案由的映射，下游就永远拿不到领域。
    （注意 `CAUSE_TO_FIELD.items()` 里键是案由、值是领域 —— 别把两者比反。）"""
    for _, cause in CAUSE_RULES:
        assert cause in CAUSE_TO_FIELD, f"{cause} 不在 CAUSE_TO_FIELD 里"


@pytest.mark.parametrize("question,expected", [
    ("离婚时加班费算不算共同财产", "婚姻家庭纠纷"),
    ("离婚时欠的借款谁来还", "婚姻家庭纠纷"),
    ("离婚后网购的东西归谁", "婚姻家庭纠纷"),
])
def test_container_cause_wins_over_specific(question, expected):
    """婚姻家庭是容器类案由：离婚析产会牵进加班费、借款、网购财产。这三句实测
    各自命中两条规则，所以把对应两条规则的先后对调，本用例必红 —— 顺序的护栏。"""
    assert tag(question) == expected


@pytest.mark.parametrize("question,expected", [
    # 含「押金」但属劳动：用人单位收押金为劳动合同法所禁，不能判成租赁
    ("公司收我押金不退", "劳动争议"),
    ("入职要交押金合法吗", "劳动争议"),
    ("公司扣我工资当押金", "劳动争议"),
    ("公司收了我整整三个月的押金", "劳动争议"),  # 动作与押金隔 8 字，窗口宁宽勿窄
    ("单位收押金合法吗", "劳动争议"),              # 「单位」「老板」是用户口语主力说法
    ("老板收押金合法吗", "劳动争议"),
    ("离职时押金没退", "劳动争议"),
    ("试用期交了押金能退吗", "劳动争议"),
    # 含「公司」但属租赁：名词性「X公司」与处所语「公司附近」都不是用人单位
    ("公司租的房子押金不退", "房屋租赁合同纠纷"),
    ("公司附近的房子押金不退", "房屋租赁合同纠纷"),
    ("公司附近租房押金要不回来", "房屋租赁合同纠纷"),
    ("装修公司不退押金", "房屋租赁合同纠纷"),
    ("租车公司不退押金", "房屋租赁合同纠纷"),
    ("搬家公司扣押金", "房屋租赁合同纠纷"),
    ("中介公司收押金", "房屋租赁合同纠纷"),
    ("共享单车公司押金退不了", "房屋租赁合同纠纷"),
    # 下面两句判租赁**不是因为标点断句**——半角逗号与全角分号都不是句界，窗口
    # 可以跨（同组「公司收了钱,不退押金」正是这条的护栏），而是因为动作必须在
    # 押金**之前**：两句的「要」都落在押金之后，三重约束里的第②条就断在这里
    ("公司不管,押金找房东要", "房屋租赁合同纠纷"),
    ("公司附近；押金要不回来", "房屋租赁合同纠纷"),
    # 含「退款」但属租赁：消费者侧的裸「退款」词元已删，只有语境词才定案由
    ("退租时房东不肯退款", "房屋租赁合同纠纷"),
    ("退租后押金退款一直不到账", "房屋租赁合同纠纷"),
    # 反向不误伤：裸「押金」「退款」仍按各自的语境落位
    ("租房押金不退怎么办", "房屋租赁合同纠纷"),
    ("房东不退押金", "房屋租赁合同纠纷"),
    ("网购到假货要求退款", "消费者权益纠纷"),
    ("商家拒绝退款", "消费者权益纠纷"),             # 删裸「退款」后按商家侧语境捞回
    ("卖家不给退款", "消费者权益纠纷"),
    ("直播买的东西不退款", "消费者权益纠纷"),
    # 主位上的「公司」要放行：代词/介词前缀（封闭集合）与书面全称都算用人单位
    ("用人单位收押金违法吗", "劳动争议"),
    ("我公司收押金", "劳动争议"),
    ("我们公司收了我押金", "劳动争议"),
    ("跟公司签合同交了押金", "劳动争议"),
    ("和公司要押金", "劳动争议"),
    ("向公司交了押金", "劳动争议"),
    ("公司不退我押金", "劳动争议"),                 # 动作「退」也在用人单位动作集里
    ("公司收了钱,不退押金", "劳动争议"),            # 半角逗号不是句界，窗口可跨
    # 反向：新放行的主体不得把偏正结构与场所语重新卷进来（含复审新造的三句）
    ("保洁公司不退押金", "房屋租赁合同纠纷"),
    ("物业公司收押金", "房屋租赁合同纠纷"),
    ("汽车公司扣押金", "房屋租赁合同纠纷"),
    # 消费者侧的场所词会与租赁题面共现，已删；相对方词后接租金/押金时让位
    ("店铺押金不退怎么办", "房屋租赁合同纠纷"),
    ("店铺租金纠纷怎么处理", "房屋租赁合同纠纷"),
    ("网店押金不退", "房屋租赁合同纠纷"),
    ("商家租金纠纷", "房屋租赁合同纠纷"),
])
def test_confusable_phrases_keep_their_cause(question, expected):
    """实测误判的回归钉：押金归劳动要「主位主体 + 前置动作 + 窗口不跨逗号句号问号」，
    退款归消费者要有交易相对方语境。每条都对应一次真实的字段级翻错（房产 ↔ 劳动法）。
    已知损失（不在此钉）：动作后置的「公司押金不退」判租赁、全角逗号分隔的动作窗口
    不跨句 —— 两者都要靠放宽约束才能救，会让上一轮的 13 句误判重开。"""
    assert tag(question) == expected


def test_generic_field_literal_is_pinned():
    """GENERIC_FIELD 是 Task 2 / Task 7 共同消费的用户可见契约值，钉字面量。"""
    assert GENERIC_FIELD == "通用"
    assert field_of(None) == "通用"


def test_none_question_is_never_guessed():
    """入参类型是 str，但上游可能把「没有问句」传成 None；实现用 `or ""` 兜住，
    行为必须是「不猜」而不是抛错（去掉兜底时报 TypeError：re.Pattern.search(None)）。"""
    assert tag(None) is None
