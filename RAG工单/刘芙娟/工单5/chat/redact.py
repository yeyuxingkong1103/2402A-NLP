"""落库前的隐私脱敏。

---

## ⚠️ 能力边界：姓名**不做**通用替换

这是本模块最要紧的一件事，写在最前面。

**中文姓名无法用正则可靠识别。** 反例是具体的：「张医生」「高血压」「李主任」
与真实姓名在字面上不可区分。无差别替换（如把 `[一-龥]{2,3}` 全换成 `***`）
会把医学名词一起打掉 —— 而「高血压」被打码会直接破坏模型理解问题所需的上下文，
代价远大于收益。

因此本模块**只做带上下文锚点的保守替换**，且只覆盖两类有严格格式的身份信息：

    手机号    (?<!\\d)1[3-9]\\d{9}(?!\\d)
    身份证    (?<!\\d)(\\d{17}[\\dXx]|\\d{15})(?!\\d)

⚠️ **MUST NOT 在任何文档或接口说明中宣称"已实现患者姓名脱敏"** —— 那是做不到的
承诺。真正可靠的姓名保护属于**接入层**（实名体系 / 登录态）的职责，
不在本模块能力内。

## 为什么正则带前后否定环视

`(?<!\\d) ... (?!\\d)` 挡住的是"更长数字串的一段被误判"：

    单看 `1[3-9]\\d{9}`，一个 15 位身份证 `110101199003071` 里的
    `1990030712` 不匹配（不以 1[3-9] 开头），但一个 20 位的订单号
    `13812345678901234567` 的前 11 位 `13812345678` **会**匹配 ——
    于是订单号被截断成 `***901234567`，一个不该动的数字被改坏了。

身份证的 15 位分支尤其危险：不加环视时，任何 15 位以上的长数字串
都会被切出 15 位来匹配。
"""

from __future__ import annotations

import re

__all__ = ["redact", "PLACEHOLDER"]

# 替换后的占位符。
#
# ⚠️ 用固定长度、无信息的 `***` 而不是 `<手机号>` 这类**标注式**占位符：
# 标注式会让模型知道"这里原本是一个手机号"，从而可能围绕它生成
# "您的号码是 XXXX"之类的话术。脱敏的目标是让模型**既不知道内容、
# 也不需要知道类别**。
PLACEHOLDER = "***"

# ⚠️ **合并成一个正则、一趟替换**，而不是两个 `sub` 接连跑。
#
# 连续两次 `sub` 时，「先替换进去的内容」会被「后一次替换」再次扫描 ——
# 而占位符 `***` 恰好不是数字，所以这里侥幸没出问题。
# 但那次侥幸不该被依赖：换一个含数字的占位符，两趟替换就会互相污染
# （第一次替换出的内容被第二次当成待匹配文本）。
# 一趟替换对每个位置只看一次，从结构上排除这种嵌套。
#
# 这与 `backend/generate/prompt.py:render` 用一趟 `_PLACEHOLDER_RE.sub`
# 而非连续三次 `replace` 是同一个取向。
#
# 两个分支各自的要点：
#   手机号  11 位、1 开头、第二位 3–9
#   身份证  18 位（末位可为 X/x）或 15 位
#           ⚠️ 18 位分支**必须写在前面** —— 正则的 `|` 从左到右尝试，
#           把 15 位写在前面会让 18 位的身份证被截成 15 位 + 剩下 3 位裸露
_REDACT_RE = re.compile(
    r"(?<!\d)1[3-9]\d{9}(?!\d)"                  # 手机号
    r"|(?<!\d)(?:\d{17}[\dXx]|\d{15})(?!\d)"     # 身份证
)


def redact(text: str) -> str:
    """把手机号与身份证号替换为 `***`。**破坏性，不可逆。**

    找不到敏感信息时原样返回（不是错误 —— 绝大多数消息都不含）。

    ⚠️ **本函数是脱敏的唯一入口。** `service.append_message` 与
    `dialogue` 落库助手消息前 MUST 都经过它，MUST NOT 只在其中一处调用 ——
    助手回复里同样可能出现用户上一轮提供的号码（模型复述）。
    """

    if not text:
        return text
    return _REDACT_RE.sub(PLACEHOLDER, text)
