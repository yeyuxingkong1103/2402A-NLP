if __name__ == "__main__":
    import argparse, json, time
    import httpx
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--output", default="data/exports/evaluation.json")
    args = parser.parse_args()
    rows = []
    with httpx.Client(timeout=120) as client:
        for item in QUESTIONS:
            started = time.perf_counter()
            response = client.post(f"{args.base_url}/api/ask", json={"question": item["question"], "language": "zh"})
            rows.append({**item, "response": response.json(), "elapsed_ms": round((time.perf_counter() - started) * 1000, 2)})
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(rows)} results to {output}")
