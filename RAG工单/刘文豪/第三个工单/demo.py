# -*- coding: utf-8 -*-
"""
工单编号：人工智能 NLP-RAG-PDF 文档的表格解析及检索优化
演示：工单03 规定的 14 个检索问题（覆盖两份招股书）
运行：python demo.py
"""
import time
from pathlib import Path

import rag

QUESTIONS = [
    ("1", "武汉力源信息技术股份有限公司本次发行股数是多少，占发行后总股本的比例是多少？"),
    ("2", "武汉力源信息技术股份有限公司本次募集资金拟投资哪些项目？"),
    ("3", "与武汉力源信息技术股份有限公司存在控制关系的关联方是谁，持股比例和本公司关系是什么？"),
    ("4", "与武汉力源信息技术股份有限公司不存在控制关系的关联方企业有哪些？"),
    ("260", "报告期内，武汉兴图新科电子股份有限公司来自军用领域的收入分别是多少？"),
    ("95", "武汉兴图新科电子股份有限公司参与制定了哪个技术标准？"),
    ("33", "报告期内，武汉兴图新科电子股份有限公司来自军用领域的收入占主营业务收入的比重分别是多少？"),
    ("34", "根据武汉兴图新科电子股份有限公司招股意向书，电子信息行业的上游涉及哪些企业？"),
    ("957", "武汉兴图新科电子股份有限公司在哪个领域已经成为重要供应商？"),
    ("793", "根据武汉兴图新科电子股份有限公司招股意向书，电子信息行业的下游主要包括哪些行业？"),
    ("795", "武汉兴图新科电子股份有限公司参与的哪个工程荣获了国家科技进步一等奖？"),
    ("543", "武汉兴图新科电子股份有限公司注册资本是多少？"),
    ("531", "武汉兴图新科电子股份有限公司法定代表人是谁？"),
    ("207", "武汉兴图新科电子股份有限公司计划使用本次发行募集资金的多少用于补充流动资金？"),
]


def main():
    col = rag.get_collection()
    lines = ["# 工单03 演示结果：表格解析及跨文档检索", "",
             "新增：招股说明书2（力源信息）解析入库；PyMuPDF find_tables 表格结构化抽取；跨文档检索带出处", ""]
    ok = 0
    for qid, q in QUESTIONS:
        t0 = time.time()
        ans, hits = rag.answer(col, q)
        dt = time.time() - t0
        src = "; ".join(f"{rag.DOC_ALIAS[h['doc']]}p{h['page']}{'+表' if h['kind']=='table' else ''}"
                        for h in hits[:3])
        print(f"[{qid}] {dt:.1f}s  {q[:30]}…\n  -> {ans[:90]}\n  命中: {src}\n")
        lines += [f"## id={qid}", f"**Q**：{q}", "", f"**A**：{ans}", "",
                  f"耗时 {dt:.1f}s；命中：{src}", ""]
        if "未找到" not in ans:
            ok += 1
    lines += ["## 汇总", f"- 直接作答：{ok}/{len(QUESTIONS)}（{ok/len(QUESTIONS)*100:.0f}%）"]
    Path("演示结果.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"命中率 {ok}/{len(QUESTIONS)} -> 演示结果.md")


if __name__ == "__main__":
    main()
