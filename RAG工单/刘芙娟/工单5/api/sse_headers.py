"""SSE 响应头。**全仓唯一的定义处。**

本模块存在的原因是 specs/009（语料入库）：它是本仓第二条 SSE 流，
需要与 `/ask` 完全相同的三个响应头。

⚠️ **MUST NOT 在任何其他地方复制这三个头。**

复制一份的代价不是"多几行"，而是：将来有人只给其中一条流加上第四个头
（比如某个代理又冒出一个新的缓冲行为），两条流的行为就不一致了 ——
而这类漂移**没有任何测试会发现**，因为每条流的测试都只看自己。
服务端日志也不会报错。它只会在某台特定的代理后面，让其中一条流
悄悄退化成"等全部完成再一次性到达"。

三条头的理由各自独立，都不是可选的。
"""

from __future__ import annotations

__all__ = ["SSE_HEADERS"]

SSE_HEADERS: dict[str, str] = {
    # 医疗内容一旦被缓存，用户可能看到**上一个问题的答案**。
    # 错配的答案比没有答案更糟。
    #
    # 对语料入库的进度流，同样的头挡住的是"看到上一个任务的状态"。
    "Cache-Control": "no-cache",
    # 让可能存在的反向代理（nginx 及其兼容层）不要缓冲响应。
    # 代理一缓冲，流式就退化成"等全部完成再一次性到达"—— 功能看着是好的，
    # 流式已经死了，而且服务端日志毫无异常，极难定位。
    #
    # 这一条对入库进度流尤其关键：一次入库是分钟级的，若被代理缓冲，
    # 用户会在几分钟里看不到任何东西，然后一次性看到全部步骤 ——
    # 而"实时高亮"正是本特性的全部价值所在。
    "X-Accel-Buffering": "no",
    # 流式应答的生命周期长于普通请求，显式声明避免中间设备提前关闭。
    "Connection": "keep-alive",
}
