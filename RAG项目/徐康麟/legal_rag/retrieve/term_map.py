#: 短语最小长度（太短的词容易误触，例如"假"）
_MIN_TRIGGER_LEN = 2


def expansions(query: str, *, limit: int = 6) -> list[str]:
    """命中的立法术语（去重、保持顺序、最多 ``limit`` 个）。"""
    text = str(query or "")
    if not text.strip():
        return []
    found: list[str] = []
    for trigger, terms in TERM_MAP.items():
        if len(trigger) < _MIN_TRIGGER_LEN or trigger not in text:
            continue
        for term in terms:
            if term not in found:
                found.append(term)
            if len(found) >= limit:
                return found
    return found


def expand_query(query: str, *, limit: int = 6) -> str:
    """把立法术语追加到查询后（供 BM25 使用）。没有命中就原样返回。"""
    extra = expansions(query, limit=limit)
    if not extra:
        return str(query or "")
    return f"{query} " + " ".join(extra)


def expand_query_logged(query: str, *, limit: int = 6) -> str:
    """带日志的版本（按项目规则：影响检索的每一步都要看得见）。"""
    extra = expansions(query, limit=limit)
    if extra:
        logger.info("[术语映射] %r -> 追加立法术语 %s", query, extra)
    return f"{query} " + " ".join(extra) if extra else str(query or "")
