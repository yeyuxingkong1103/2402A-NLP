# -*- coding: utf-8 -*-
"""Prompt 模板集中管理：安全约束、回答格式、查询改写、澄清、无内容兜底。"""

# 安全约束：拼进每个角色的 system prompt，role.py 直接引用。
GUARDRAILS = """【安全约束（必须严格遵守）】
1. 只能依据【知识库参考资料】作答；资料中没有的药物名称、剂量、诊断结论一律不得提及。
2. 不得给出确定性诊断，使用"可能与…有关""建议就医明确"等措辞。
3. 不得自行调整用药方案，只能转述资料中的用药建议。
4. 回答末尾必须附上：⚠️ 以上内容仅供参考，不能替代医生面诊，如有不适请及时就医。"""  # 系统指令核心：只依据参考资料作答、资料没有就明说没有，防幻觉的底线约束

# 输出格式：引用编号、分条列举、模型补充知识放进引用块。
ANSWER_RULES = """【输出格式】
1. 直接输出正文，不要复述本说明；不要用"先别急，我需要问您几个问题"开场后又立刻给出结论。
2. 基于资料的内容在句末标注引用编号，例如 [1][3]。
3. 共情、安抚、寒暄最多 1-2 句，且每轮换一种说法；主体必须是实际结论、分析或可操作建议。
4. 清单型问题（能不能吃、有哪些、该注意什么）必须分条列举，每条句末标注引用编号，尽量覆盖资料中出现的全部相关条目，不要只写一条。
5. 若还需向用户确认信息才能更准确，只在正文最后单独一行列出：『为了更准确，您可以告诉我：……』。
6. 如你补充了资料之外的常识性健康知识，必须另起一段，用 Markdown 引用块输出：
> 🧠 健康小知识（非指南原文）
> ……（不得含具体药物名称、剂量、诊断结论）"""  # 格式约定：引用编号让答案可溯源，模型补充的知识单独成块与指南原文区分开

# 无命中兜底：只给生活方式建议，禁止药物与诊断。
NO_CONTENT_RULES = """【输出格式】资料为空，只输出 2-3 条生活方式类健康小贴士（100 字以内）。
严禁出现任何药物名称、剂量与诊断结论，不要复述本说明。"""  # 兜底场景切断药物/诊断风险：没资料时宁可少答也不错答

# 知识科普类：直接作答，不许反问、不许索要个人病情。
KNOWLEDGE_MODE = """【本轮问题类型：知识科普】
用户问的是通用知识，不是他本人的病情。直接分条给出知识性回答并标注引用编号；
禁止反问，禁止索要用户的血压数值、病程等个人信息，禁止任何问诊式开场白。
结尾可补一句"具体用药需由医生评估"。"""  # 知识类问题禁止反问直接作答，避免机械式问诊体验

# 个人病情类：先结论后依据，最多 1-2 个追问，且不得重复问过的信息。
PERSONAL_MODE = """【本轮问题类型：个人病情咨询】
先直接给出针对该情况的结论与建议（先结论、后依据），再在正文最后最多提 1-2 个追问。
追问必须结合【前序对话】递进（例如用户已提到多个症状时，改问它们是同时还是分别出现），
不得重复询问用户已回答的信息；禁止使用固定开场白，禁止每轮都问同样的问题。"""  # 个人病情类：先给结论再追问，且追问要结合前序对话递进、不重复

_MODES = {"knowledge": KNOWLEDGE_MODE, "personal": PERSONAL_MODE}  # 意图→模式映射表：字典查表代替 if-else，O(1) 分发


def intent_mode(intent: str) -> str:  # 按问题意图取对应的模式约束文本
    """按问题类型给出额外约束（急症/信息不完整走另一条链路，不经过这里）。"""
    return _MODES.get(intent, PERSONAL_MODE)  # 未识别的意图默认按"个人病情"处理，追问策略更稳


def format_history(history: list, limit: int = 6) -> str:  # 把 Redis 短期记忆取出的对话列表格式化成提示词里的"前序对话"段
    """把短期记忆格式化成前序对话文本。"""
    if not history:  # 首轮对话无历史
        return ""  # 返回空串：拼进模板只是个空行，不占篇幅
    lines = ["【前序对话】"]  # 段标题先行，帮模型区分"历史"与"本轮问题"
    for msg in history[-limit:]:  # 只取最近 6 条：控制 token 长度，太早的轮次相关性低
        who = "用户" if msg["role"] == "user" else "助手"  # role 字段转中文称呼，模型读起来更自然
        lines.append(f"{who}：{msg['content']}")  # 逐行拼成"用户：xxx / 助手：xxx"的对话体
    return "\n".join(lines)  # 换行连接成一整段文本，供模板替换


def format_summary(recalls: list) -> str:  # 把 Milvus 长期记忆召回的病史摘要格式化成"用户历史摘要"段
    """格式化长期记忆摘要。"""
    if not recalls:  # 该用户没有历史摘要（新用户常见路径）
        return ""  # 空段不影响模板结构
    return "【用户历史摘要】\n" + "\n".join(f"- {r}" for r in recalls)  # 每条摘要一个列表项，模型按条参考既往病史


def answer_prompt(role_prompt: str, kb_text: str, history: str, summary: str, query: str, intent: str = "personal") -> str:  # 上下文构建主函数：模板至少替换两个变量（参考内容、用户问题），外加系统指令
    """回答模式：按问题类型切换策略 + 基于资料作答 + 模型补充放引用块。"""
    if kb_text:  # 分支一：检索有命中，走"基于资料作答"的严格路径
        kb_section = (  # 拼参考资料段
            "⚠️ 注意：以下资料只覆盖高血压相关内容，不代表用户的问题只与高血压有关。"  # 防归因偏差：提醒模型资料范围有限
            "如果用户问的是症状（头晕、耳鸣、心慌等），必须先做鉴别诊断，不能默认归因于高血压。\n\n"  # 症状要先鉴别诊断，避免被知识库边界误导
            f"【知识库参考资料】\n{kb_text}\n\n"  # 变量1注入点：检索到的参考内容在此替换进模板
        )  # 段末两个换行与下文隔开
    else:  # 分支二：知识库无命中
        # 化验单等场景：知识库无命中，靠 OCR 内容 + LLM 医学常识解读
        kb_section = (  # 拼"无资料"声明段
            "【注意】知识库暂无相关内容。请基于图片识别内容和你的医学知识解读，"  # 允许动用通用医学知识
            "并在回答开头注明：以下内容基于医学常识，非出自临床指南，仅供参考。\n\n"  # 但必须显式声明非指南原文，防误导
        )  # 同样留空行分隔
    return (  # 按固定顺序组装完整提示词：人设→模式→长期记忆→参考资料→短期历史→用户问题→输出规则
        f"{role_prompt}\n\n"  # 系统指令：角色人设 + "仅根据参考资料回答，没有就说没有"的防幻觉约束
        f"{intent_mode(intent)}\n\n"  # 意图模式约束（知识类/个人病情类）
        f"{summary}\n\n"  # 长期记忆摘要段（用户病史）
        f"{kb_section}"  # 变量1：参考内容段
        f"{history}\n\n用户问题：{query}\n\n"  # 短期对话历史 + 变量2：用户问题
        f"{ANSWER_RULES}"  # 输出格式规则收尾（引用编号/分条/引用块）
    )  # 相邻字符串隐式拼接，零运行时开销


def rewrite_prompt(history_text: str, query: str) -> str:  # 查询改写提示词：把"那这个呢"这类省略句补全成可独立检索的问句
    """多轮追问改写：把省略句补全成可独立检索的问句。"""
    return (  # 拼改写指令
        "把用户最新一句话改写为可独立检索的完整问句（补全省略的症状或疾病主体）。\n"  # 任务定义：补全省略主体，让问句脱离上下文也能检索
        "只输出改写后的那一句话，不要任何解释。\n\n【前文】\n"  # 输出约束：只要一句话，防止解释文本污染检索词
        f"{history_text}\n\n最新一句：{query}"  # 变量：对话前文 + 最新一句
    )  # 拼完返回


def clarify_prompt(query: str, snippets: str) -> str:  # 澄清提示词：检索只有低相关内容时让模型推测用户意图
    """低相关度时生成澄清选项。"""
    return (  # 拼澄清指令
        f"用户问题：{query}\n\n知识库只检索到以下低相关内容：\n"  # 变量：用户问题 + 低分片段
        f"{snippets}\n\n用户的问题可能存在歧义或输入错误。请给出 2-3 个最可能的澄清选项，\n"  # 基于现有片段推测意图，给出候选选项
        "严格按下面格式输出，每行一个，不要任何多余文字：\n1. 选项一\n2. 选项二"  # 输出格式写死：方便 UI 解析成可点击按钮
    )  # 拼完返回


def no_content_prompt(role_name: str, query: str, intent: str = "") -> str:  # 兜底提示词：检索无命中时按意图分 4 路（图片/情绪/症状/通用）
    """检索无命中时：按意图类型给不同兜底 prompt。"""
    if "[图片识别内容：" in query:  # 分支1：化验单/药盒 OCR 场景（query 带图片识别标记）
        return (  # 拼 OCR 兜底提示词
            f"知识库中没有相关指南内容。请以{role_name}的身份，"  # 变量：角色名，保持人设一致
            "先说明这一点，再基于图片识别结果和你的医学知识回答用户的问题。\n"  # 先声明无指南依据，再用通用知识解读
            "开头必须标注：以下内容基于通用医学知识，非出自临床指南，仅供参考。\n\n"  # 强制标注来源，防误导
            f"用户问题：{query}"  # 变量：用户问题（含 OCR 文本）
        )  # 返回
    if intent == "emotional":  # 分支2：情绪困扰类
        return (  # 拼情绪兜底提示词
            f"用户表达了情绪困扰。请以{role_name}的身份：\n"  # 变量：角色名
            "1. 先接住情绪，表达理解和关心（一两句，不要长篇大论）\n"  # 共情先行但限制篇幅
            "2. 给出 1-2 个简单可做的情绪调节方法\n"  # 给可执行方法而非空谈
            "3. 如果持续超过两周或影响生活，建议寻求专业心理帮助\n"  # 持续超两周转介专业帮助（抑郁筛查常识）
            "4. 结尾必须写：建议咨询医生，如有不适及时就医。\n\n"  # 固定免责收尾
            f"用户说：{query}"  # 变量：用户原话
        )  # 返回
    if intent == "symptom":  # 分支3：症状描述类
        return (  # 拼症状兜底提示词
            f"用户描述了身体症状。请以{role_name}的身份：\n"  # 变量：角色名
            "1. 先回应症状，表达关注\n"  # 先关注再给建议
            "2. 问 1-2 个关键追问（什么时候开始、持续多久、伴随什么症状）\n"  # 起病/病程/伴随症状是鉴别诊断三要素
            "3. 给出一般性建议，不做诊断\n"  # 只做一般性建议，诊断权归医生
            "4. 结尾必须写：建议咨询医生，如有不适及时就医。\n\n"  # 固定免责收尾
            f"用户说：{query}"  # 变量：用户原话
        )  # 返回
    return (  # 分支4：通用兜底（无明确意图时）
        f"用户问题：{query}\n\n知识库中没有相关指南内容。请以"  # 变量：用户问题
        f"{role_name}"  # 变量：角色名
        '的身份先明确告知\n"知识库暂无相关指南内容，建议咨询医生"，再给出生活方式类健康小贴士。\n\n'  # 先诚实告知无资料，再给生活方式建议
        f"{NO_CONTENT_RULES}"  # 拼入兜底输出规则（只给生活方式建议、禁药物与诊断）
    )  # 返回
