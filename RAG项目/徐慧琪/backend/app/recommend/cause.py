"""案由标签与专业领域映射。

为什么用纯规则而不是模型（技术方案 6.4 定稿）：案由是下游「推荐律师」与
「费用区间」的共同输入，判错会把用户导向错误的领域与收费口径。规则可穷举
测试、可解释、零成本；模型判错时没有便宜的发现手段。
"""
from __future__ import annotations

import re

# 案由认不出时的兜底领域：不给具体领域，但律师卡片照常展示（设计 §七）
GENERIC_FIELD = "通用"

# 案由规则。**顺序是语义的一部分**，命中即返回。婚姻家庭排在最前，不是因为它
# 更「具体」（五个案由是平级类目），而是因为它是容器类案由：离婚析产会把加班费、
# 借款、网购财产与租赁押金一并牵进来，所以含婚姻家庭词元的问句整体归婚姻家庭。
# 「押金」在劳动侧只在用人单位语境下成立（劳动合同法禁止收押金），所以劳动规则
# 用的是带上下文的模式而非裸词元，以免抢走「租房押金」「房东不退押金」这类问句。
CAUSE_RULES: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"(离婚|抚养|抚养费|夫妻共同财产|婚前财产)"), "婚姻家庭纠纷"),
    # 押金归劳动要有三重约束，缺一条就把房产问句误判成劳动法：①主体是「用人单位」
    # 本身，或是处在主位上的「公司|单位|老板」——左边界只排除紧贴汉字的偏正结构
    # （装修/搬家/租车/中介/共享单车公司）与处所语（公司附近）；代词与介词
    # （我你他咱们和跟向同）之后是真主语，放行。这两类都是封闭集合，不会像
    # 字符黑名单那样越漏越多。②主体与押金之间要有 收/扣/交/退/要 这类用人单位
    # 动作，且动作必须在押金**之前**——「公司押金不退」这类后置语序是已知损失。
    # ③窗口不跨逗号/句号/问号（曾扩到分号顿号半角问号，实测只赔不赚故退回）。
    # 入职/离职/试用期是另一条无歧义入口
    (re.compile(r"(拖欠工资|加班费|经济补偿|违法辞退|劳动合同|社保|工伤"
                r"|(?:事业单位|用人单位|(?:(?<![一-鿿])|(?<=[我你他咱们和跟向同]))"
                r"(?:公司|单位|老板))[^，。？]{0,8}"
                r"(?:收|扣|交|退|要)[^，。？]{0,8}押金"
                r"|(?:入职|离职|试用期)[^，。？]{0,8}押金)"), "劳动争议"),
    # 「退款」曾作为裸词元放在这里，会把「退租时房东不肯退款」误判成消费者——
    # 该词在消费者语境之外同样常用。判断交给语境词：商家侧补「商家|卖家」等
    # 交易相对方（用户投诉时最先说出的是对方是谁），宁可漏判「我要退款怎么办」。
    # 只留相对方词：场所词（店铺/网店/直播间）与租赁题面天然共现（店铺租金纠纷），
    # 会抢走房产问句；「商家|卖家」后紧跟租金/押金同理，用负向断言让位给租赁
    (re.compile(r"(网购|假货|退货|三倍赔偿|消费者|直播"
                r"|(?:商家|卖家)(?![^，。？]{0,4}(?:租金|押金)))"), "消费者权益纠纷"),
    (re.compile(r"(借款|借钱|欠条|借条|利息|民间借贷)"), "民间借贷纠纷"),
    (re.compile(r"(租房|押金|房东|承租人|租金|退租)"), "房屋租赁合同纠纷"),
]

# 案由 → 专业领域。演示用映射表，正式运营前随真实律师名录一起替换
CAUSE_TO_FIELD: dict[str, str] = {
    "婚姻家庭纠纷": "婚姻家庭",
    "劳动争议": "劳动法",
    "消费者权益纠纷": "消费者权益",
    "民间借贷纠纷": "金融与借贷",
    "房屋租赁合同纠纷": "房产与建设工程",
}


def tag(question: str) -> str | None:
    """问句 → 案由标签；认不出返回 None（不猜）。"""
    text = question or ""
    for pattern, cause in CAUSE_RULES:
        if pattern.search(text):
            return cause
    return None


def field_of(cause: str | None) -> str:
    """案由 → 专业领域；认不出给 GENERIC_FIELD（卡片仍能展示，见设计 §七）。"""
    if cause is None:
        return GENERIC_FIELD
    return CAUSE_TO_FIELD.get(cause, GENERIC_FIELD)
