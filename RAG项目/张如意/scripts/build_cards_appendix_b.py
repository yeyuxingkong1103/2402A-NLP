def norm_days(s):
    """天数写法归一：`7d~10d` -> `7 d~10 d`（**带空格**，与 pre_harvest_interval 口径一致）。

    为什么需要：三份标准原文写法本就不统一——辣椒写「施药间隔7d~10d」，大蒜写
    「施药间隔 7 d~10 d」。加上我早先抽 interval_days 时 `.replace(" ", "")` 抹了空格，
    结果**同一条记录里两个字段两种写法**。

    注意：**只归一派生字段，`raw` 一律保留原文原样**——逐字照抄的要求由 raw 承载，
    检索字段才需要格式统一。
    """
    if not s:
        return s
    s = re.sub(r'(\d)\s*d(?![a-zA-Z])', r'\1 d', str(s))   # 数字与 d 之间补空格
    s = re.sub(r'\s*~\s*', '~', s)                          # 波浪号两侧不留空格
    return re.sub(r'\s+', ' ', s).strip()


def _title(crop, obj, timing, stage):
    """标题模板：有生育期列的（辣椒）用 {作物}{生育期}{对象}；没有的用 {作物}{对象}（{防治适期}）。
    防治对象前已冠作物名时不重复（如「黄瓜白粉病」）。"""
    if stage:
        return f"{crop}{stage}{obj}化学防治方案"
    base = obj if obj.startswith(crop) else f"{crop}{obj}"
    suffix = "" if timing in ("—", "", None) else f"（{timing}）"
    return f"{base}{suffix}化学防治方案"


def build():
    """按 PLANS 逐作物、逐防治对象生成附录 B 防治方案知识卡。

    每条 (防治对象, 防治适期) 生成一张卡：同一行的多个备选方案放进同一张卡
    的 chemicals[]；安全间隔期/每茬最多使用次数按药剂名从 INTERVAL 查表
    （复配剂按成分分列后用「；」拼接）；施药间隔从原文 raw 里正则抽取。
    全部卡 is_high_risk=True（农药剂量与安全间隔期属高危字段）。
    返回：list[dict] 知识卡列表。
    """
    cards = []
    for crop, plans in PLANS.items():       # 逐作物
        std_no, std_name, _ = STD[crop]
        iv = INTERVAL[crop]                 # 该作物「药剂名 → (安全间隔期, 每茬最多使用次数)」查表
        for obj, timing, chems in plans:    # 逐防治对象：对象名/防治适期/药剂方案列表
            # 表B.1(续) 所在页：黄瓜 p21=美洲斑潜蝇/瓜蚜；辣椒 p21=茶黄螨；大蒜附录B仅 p20 一页
            P21 = {"黄瓜": ("美洲斑潜蝇", "瓜蚜"), "辣椒": ("茶黄螨",), "大蒜": ()}
            page = 21 if obj in P21[crop] else 20
            chemicals, missing = [], []
            for i, (key, product, dose, dil, method, comp, raw) in enumerate(chems):
                # key 可为字符串（单成分）或列表（复配剂，原表清单按成分分列多条）
                keys = key if isinstance(key, list) else [key]
                hit = [(k, iv.get(k, (None, None))) for k in keys]  # 按药剂名查安全间隔期表
                if len(hit) == 1:
                    phi, mx = hit[0][1]     # 单成分：直接取 (安全间隔期, 每茬最多使用次数)
                else:
                    # 复配剂：两个成分分别查表后用「；」拼接成一条字段值
                    phi = "；".join(f"{k} {v[0]}" for k, v in hit if v[0])
                    mx = "；".join(f"{k} {v[1]}" for k, v in hit if v[1]) or None
                # 施药间隔（两次施药之间），原文写在防治方法里
                m = re.search(r'施药间隔\s*([0-9.]+\s*d(?:\s*~\s*[0-9.]+\s*d)?)', raw)
                chemicals.append({
                    "product": product,
                    "active_ingredient": None,
                    "dose": dose,
                    "dilution": dil,
                    "method": method,
                    "interval_days": norm_days(m.group(1)) if m else None,
                    "pre_harvest_interval": norm_days(phi) or None,
                    "max_uses_per_season": mx,
                    "companion_control": comp,
                    "raw": raw,
                })
                if not phi:                 # INTERVAL 表查不到该药剂 → 记入缺失字段
                    missing.append(f"chemicals[{i}].pre_harvest_interval")
            # 高危原因：附录B 全部含农药剂量与安全间隔期；有使用次数的再补一条
            reasons = ["农药剂量", "安全间隔期"]
            if any(c["max_uses_per_season"] for c in chemicals):
                reasons.append("每茬最多使用次数")
            n = sum(1 for c in cards if c["crop"] == crop) + 1  # 同作物内流水号（拼 card_id 用）
            quote = "｜".join([obj, timing] + [c["raw"][:60] for c in chemicals])[:200]  # 原文引文，截断到 200 字
            cards.append({
                "card_id": f"{std_no.replace('/','').replace(' ','').replace('-','-')}-p{page}-c{n:02d}",
                "std_no": std_no, "std_name": std_name, "authority_level": 1, "year": 2011,
                "region": "全国", "crop": crop, "crop_alias": [],
                "growth_stage": STAGE.get(crop, {}).get(obj),
                # 枚举见 parse_pdf_to_knowledge.md 第 3 节：只有「病虫害防治」，无「病害防治/虫害防治」。
                # 病 vs 虫 的细分由 subtype 承载。
                "knowledge_type": "杂草防治" if obj == "杂草" else "病虫害防治",
                "pest_kind": ("杂草" if obj == "杂草" else
                              ("虫害" if obj in ("棕榈蓟马", "瓜绢螟", "美洲斑潜蝇", "瓜蚜", "蚜虫",
                                                "棉铃虫、烟青虫", "茶黄螨", "种蝇", "刺足根螨",
                                                "豌豆潜叶蝇", "蓟马") else "病害")),
                "type_group": "病虫草害",
                "subtype": obj,
                "title": _title(crop, obj, timing, STAGE.get(crop, {}).get(obj)),
                "symptoms": None,
                "trigger": timing,
                "measures": [{"type": "化学防治", "text": c["raw"]} for c in chemicals],
                "chemicals": chemicals,
                "fertilizer": None, "precautions": None,
                "record_form": None,
                "is_high_risk": True,
                "high_risk_reasons": reasons,
                "needs_human_review": True,
                "needs_verification_hint": True,
                "source": {"std_no": std_no, "section": "附录B 表B.1", "page": page,
                           "channel": "vision", "quote": quote},
                "ocr_uncertain": OCR[crop],
                "missing_fields": missing,
                "in_scope": True,
            })
    return cards


