def main() -> int:
    with io.open(DOC, encoding="utf-8") as fh:
        lines = fh.readlines()

    before = sum(line.count("（待填）") for line in lines)
    filled: list[str] = []
    problems: list[str] = []

    for case_id, text in FILL.items():
        pattern = re.compile(r"^\|\s*`" + re.escape(case_id) + r"`\s*\|")
        hits = [i for i, line in enumerate(lines) if pattern.match(line)]
        if len(hits) != 1:
            problems.append(f"{case_id}: 命中 {len(hits)} 行（要求恰好 1 行）")
            continue
        idx = hits[0]
        if not lines[idx].rstrip().endswith("| （待填） |"):
            problems.append(f"{case_id}: 行尾不是「| （待填） |」⇒ {lines[idx].rstrip()[-40:]}")
            continue
        if lines[idx].count("（待填）") != 1:
            problems.append(f"{case_id}: 该行出现 {lines[idx].count('（待填）')} 次「（待填）」")
            continue
        lines[idx] = lines[idx].replace("（待填）", text)
        filled.append(case_id)

    if problems:
        print("!! 中止，未写盘：")
        for item in problems:
            print("   -", item)
        return 1

    with io.open(DOC, "w", encoding="utf-8", newline="") as fh:
        fh.writelines(lines)

    after = sum(line.count("（待填）") for line in lines)
    print(f"已回填 {len(filled)} 条用例：{'、'.join(filled)}")
    print(f"「（待填）」数量：{before} -> {after}（减少 {before - after}）")
    print(f"文档：{DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
