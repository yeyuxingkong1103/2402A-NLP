# 已知**漏判**（第四批复核对"知情接受"的代价那侧的要求）：这些问句确实在问价，
# 但省略了法律服务语境，按判据**应当**不命中。写成断言而不是注释，是为了让代价
# 可见 —— 谁想放宽语境层，得先在这里改掉几行并说明理由。
KNOWN_MISSES = [
    "你们收费怎么算",
    "先给我个报价",
    "要花几万块钱吗",
    "计费方式是怎样的",
]


@pytest.mark.parametrize("question", KNOWN_MISSES)
def test_known_misses_are_the_accepted_cost(question):
    assert is_price_intent(question) is False


@pytest.mark.parametrize("question", POSITIVE_SAMPLES)
def test_price_questions_hit(question):
    assert is_price_intent(question) is True


@pytest.mark.parametrize("question", NEGATIVE_SAMPLES)
def test_non_price_questions_miss(question):
    assert is_price_intent(question) is False


def test_every_rule_is_alive():
    """每条规则至少被一条正例命中 —— 否则它是一条死规则：读代码时看着像护栏，
    实际永远不参与判断，而删除它对任何用例都没有影响（本项目抓过多次的
    「不可能失败的测试」在这里的反向形态：没被覆盖的规则 = 没被覆盖的判据）。"""
    for pattern in PRICE_INTENT_RULES:
        assert any(pattern.search(q) for q in POSITIVE_SAMPLES), \
            f"规则 {pattern.pattern} 没有任何正例命中，要么补正例要么删掉它"


def test_every_positive_sample_carries_legal_context():
    """每条正例都必须自带法律服务语境词。

    这条挡的是一种本末倒置的修法：往正例里塞一条**通用**问价句（「你们收费怎么算」），
    它按判据本就该被漏判，于是用例变红，而红了的"修法"往往是回头去删掉语境层 ——
    把判据改回那个会误伤非法律问价题的版本。正例集只放"应该命中"的句子，
    该命中 = 问价词 **且** 语境，这一条把这个前提钉死。
    """
    from app.recommend.price_intent import LEGAL_CONTEXT_RULES

    for question in POSITIVE_SAMPLES:
        assert any(p.search(question) for p in LEGAL_CONTEXT_RULES), \
            f"正例缺法律语境词，它按判据本不该命中：{question}"


def test_every_context_rule_is_alive():
    """语境规则同 test_every_rule_is_alive：没被任何正例命中的规则 = 没被覆盖的判据。"""
    from app.recommend.price_intent import LEGAL_CONTEXT_RULES

    for pattern in LEGAL_CONTEXT_RULES:
        assert any(pattern.search(q) for q in POSITIVE_SAMPLES), \
            f"语境规则 {pattern.pattern} 没有任何正例命中"


def test_known_false_positive_is_an_accepted_cost():
    """已知误判面，照实钉住：「价格欺诈」是消费者在问法律怎么办，不是在问价。

    保留它的理由是裁决点名要「价格」这个词；代价落在**可接受**的一侧 ——
    多一块费用信息与一次费用调用，而不是错数（区块里的数字仍要过 fees 的数值
    回查）。这条用例把它写成断言，是为了让误判面**可见**：谁想收紧「价格」这条
    规则，得先在这里改掉一行并说明理由，而不是悄悄改词表。
    """
    assert is_price_intent("商家价格欺诈怎么赔偿") is True
