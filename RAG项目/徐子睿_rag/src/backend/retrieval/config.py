# -*- coding: utf-8 -*-
"""retrieval/config.py —— 检索链路的调参常量与规则表。

在链路中的位置：
    retrieval 包内各模块共用这些常量；本文件不导入同包其他模块，是依赖的最内层。

包含三组内容：
    召回与融合参数  VECTOR_K / KEYWORD_K / RRF_K / KEYWORD_WEIGHT / VECTOR_THRESHOLD
    结果与预算参数  DEFAULT_CANDIDATES / DEFAULT_RESULTS / DEFAULT_CONTEXT_CHARS / DEFAULT_SNIPPET_CHARS
    文本处理资源    停用词表 STOP_WORDS、分词单元正则 TOKEN_RE、查询改写规则 REWRITE_RULES

其中 RRF_K=60 与 KEYWORD_WEIGHT=2.5 是排序质量的关键参数，注释里写明了取值理由。
"""
from __future__ import annotations

import os
import re

VECTOR_K = 20           # 向量路召回的候选数（取 20 是为了给后面的融合和精排留足挑选空间）
KEYWORD_K = 20          # BM25 路召回的候选数，与向量路对称
RRF_K = 60              # RRF 平滑常数。取 60 是 RRF 论文的常用默认值：它压平了头部排名的差距，
                        # 避免第 1 名对融合结果的支配过强，让两路都命中的片段才能明显胜出
KEYWORD_WEIGHT = 2.5    # 关键词路权重 λ。>1 表示更信任字面匹配 —— 国标文档里"净化处理装置"
                        # 这类专业术语的精确出现，比语义相似更能说明相关性。
                        # 这个值是网格搜索调出来的（见《项目总览.md》V2 迭代）
VECTOR_THRESHOLD = 0.5  # 向量召回的最低余弦相似度。低于此值的候选在召回阶段就直接丢掉，从源头减少噪声。
                        # 它同时是"拒答"的实际门限：候选被过滤光（且关键词路也没命中）时，
                        # server/answer.py 会因"检索无结果"返回固定拒答文案。
                        #
                        # 已知局限（2026-09-29 实测，勿误以为它是万能分界线）：
                        # 余弦阈值无法把"对口"与"离题"完全分开 —— 在重建的 422 块库上，
                        # 3 道对口题的最高余弦为 0.733/0.847/0.741，而离题问题"今天天气怎么样？"
                        # 也有 0.588（高于部分对口片段）、"请编造一个不存在的答案"为 0.451。
                        # 另测过把门限降到 0.25 或提到 0.65：降门限对 recall/MRR 毫无影响
                        # （top20 已取满且分数普遍高，门限不参与过滤），却会让 0.451 那类问题
                        # 越闸被回答；提门限反而三项指标都更好，但该值是在同一批 5 条数据上挑的，
                        # 属过拟合，未经验证不能采用。要动这个值，请先扩充评测集再定。
                        # （精排阶段另有一道 0.5 的低分过滤，见 retrieval/context.py，量纲不同不要混用）
DEFAULT_CANDIDATES = 15 # RRF 融合后进入精排的候选数
DEFAULT_RESULTS = 5     # 精排后最终返回的结果数
DEFAULT_CONTEXT_CHARS = 3600  # 拼给大模型的上下文总字符预算，防止提示词过长超出模型上下文窗口
DEFAULT_SNIPPET_CHARS = 800   # 单条片段截断长度：超过这个长度的部分对回答帮助有限，切掉省预算
CHAT_URL = os.getenv("OLLAMA_CHAT_URL", "http://localhost:11434/api/chat")
RERANK_MODEL = os.getenv("RERANK_MODEL", os.getenv("LLM_MODEL", "qwen2:7b"))  # 精排复用同一个本地模型

# 中文停用词表：这些词几乎每篇文档都有，参与 BM25 计算只会稀释真正有区分度的术语
STOP_WORDS = set("的了是在与和及或等中为对从将把被啊吧呢吗，。；：、！？\"''（）【】《》·—…　 \t\n\r")
# 分词单元：连续的字母数字，或连续的汉字。用它过滤掉分词器可能产出的纯符号碎片
TOKEN_RE = re.compile(r"[A-Za-z0-9]+|[一-鿿]+")

# 查询改写规则表：口语问法 → 文档里实际使用的术语。
# 为什么用规则而不是让大模型改写：规则快、零成本、结果可解释、可复现，
# 而且答辩时能明确指出"是哪条规则救回了这题"（见《代码说明.md》第四章第 3 节）。
# 例：用户问"净化装置有哪些功能"，向量路可能理解，但 BM25 路需要"过滤/干燥/吸附"
# 这些文档里的原词才能命中，所以在这里显式补全。
REWRITE_RULES = {
    "净化处理装置": ["净化处理装置", "过滤", "干燥", "吸附", "低温冷却", "精馏", "功能"],
    "净化装置": ["净化装置", "净化处理装置", "过滤", "干燥", "吸附", "低温冷却", "精馏", "功能"],
    "回收装置": ["回收装置", "回收", "净化", "功能"],
    "回充装置": ["回充装置", "回充", "功能"],
    "循环再利用": ["循环再利用", "现场检测", "回收", "净化", "回充"],
    "绝缘油": ["绝缘油", "溶解气体", "气相色谱", "测定法"],
    "气相色谱": ["气相色谱", "测定法"],
    "SF6": ["SF6", "六氟化硫"],
    "六氟化硫": ["六氟化硫", "SF6"],
    "回收率": ["回收率", "要求"],
}
