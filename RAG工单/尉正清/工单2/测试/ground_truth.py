def _normalize(text):
    """归一化：去掉 Markdown 强调符、千分位逗号、空白和全角标点。"""
    for ch in ("*", " ", "\n", "\t", ",", "，", "、", "：", ":", "（", "）",
               "(", ")", "《", "》", "|", "　"):
        text = text.replace(ch, "")
    return text


def check_answer(qid, answer):
    """返回 (是否全对, 命中的事实点数, 总事实点数)。"""
    norm = _normalize(answer or "")
    facts = GROUND_TRUTH[qid]["facts"]
    hit = sum(1 for group in facts
              if any(_normalize(pat) in norm for pat in group))
    return hit == len(facts), hit, len(facts)


def check_retrieval(qid, pages):
    """检索命中：正确来源页出现在召回的页码里（Hit@K）。"""
    return bool(set(pages) & set(GROUND_TRUTH[qid]["source_pages"]))
