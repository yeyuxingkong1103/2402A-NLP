def norm_page(doc: fitz.Document, page_no: int) -> str:
    return normalize(doc[page_no - 1].get_text("text"))


def find_pages_with_text(doc: fitz.Document, text: str, cap: int = 10) -> list[int]:
    needle = normalize(text)
    hits = []
    for i in range(1, doc.page_count + 1):
        if needle and needle in norm_page(doc, i):
            hits.append(i)
            if len(hits) >= cap:
                break
    return hits


def page_carries(pt: str, kw: str) -> bool:
    """页级「承载」判定：转发到 测试/common/golden.py::page_carries（单一实现）。"""
    return G.page_carries(pt, kw)


def render_evidence_images(docs: dict[str, fitz.Document]) -> dict:
    OUT_IMG.mkdir(parents=True, exist_ok=True)
    info = {}
    pdf2 = docs["招股说明书2"]
    for page_no, tag in ((39, "p39_组织结构图_2x"), (72, "p72_应用结构与增长_2x")):
        pix = pdf2[page_no - 1].get_pixmap(matrix=fitz.Matrix(2, 2))
        p = OUT_IMG / f"{tag}.png"
        pix.save(p)
        info[tag] = {"path": str(p.relative_to(ROOT)).replace("\\", "/"),
                     "size": [pix.width, pix.height],
                     "sha256_16": hashlib.sha256(p.read_bytes()).hexdigest()[:16]}
    figures = []
    for xref, tag, role in ((1692, "p72_条形图_增长率_xref1692", "条形图：2008 年中国 IC 市场各应用行业增长率"),
                            (1693, "p72_饼图_应用结构_xref1693", "3D 饼图：2008 年中国 IC 市场应用结构")):
        img = pdf2.extract_image(xref)
        p = OUT_IMG / f"{tag}.png"
        p.write_bytes(img["image"])
        figures.append({"xref": xref, "role": role, "width": img["width"], "height": img["height"],
                        "ext": img["ext"],
                        "sha256_16": hashlib.sha256(img["image"]).hexdigest()[:16],
                        "path": str(p.relative_to(ROOT)).replace("\\", "/")})
    info["figures"] = figures
    return info


