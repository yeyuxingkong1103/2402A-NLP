def relation_canonical(name: str) -> str:
    """把抽取器给出的关系名归并到规范关系名；无法归并时原样返回并标记非规范。"""
    return RELATION_ALIASES.get(str(name), str(name))


def is_valid_relation(name: str) -> bool:
    """是否为 schema 内登记的规范关系。"""
    return relation_canonical(name) in RELATION_TYPES


def entity_type_zh(key: str) -> str:
    """实体类型键 → 中文名（未知类型原样返回）。"""
    info = ENTITY_TYPES.get(str(key))
    return str(info["zh"]) if info else str(key)


def group_of_relation(name: str) -> str:
    """关系 → 图例分组名（未知关系归到「其它」）。"""
    canonical = relation_canonical(name)
    for group, members in RELATION_GROUPS.items():
        if canonical in members:
            return group
    return "其它"


def schema_dict() -> dict[str, Any]:
    """Schema 的 JSON 序列化（写进 graph.json，供前端图例与文档自证）。"""
    return {
        "schema_version": SCHEMA_VERSION,
        "work_order": WORK_ORDER,
        "entity_types": ENTITY_TYPES,
        "relation_types": RELATION_TYPES,
        "relation_groups": RELATION_GROUPS,
        "relation_aliases": RELATION_ALIASES,
    }
