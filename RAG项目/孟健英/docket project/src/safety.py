def emergency_hits(text: str) -> list:  # 急症检测：返回命中的关键词列表
    """返回命中的急症关键词列表。"""
    return [w for w in EMERGENCY_WORDS if w in text]  # 纯子串匹配，词表小所以毫秒级；常见错别字（胸通/心口痛）也在表里直接命中

def unverified_drugs(answer: str, kb_text: str) -> list:  # 药物白名单校验：找回答里有、资料里没有的药名
    """找出回答里提到、但知识库原文没有的药物名（白名单校验）。"""
    return [d for d in DRUG_LEXICON if d in answer and d not in kb_text]  # 双重子串判断：回答提到且资料未提及 → 疑似模型编造，需告警

def drug_warning(drugs: list) -> str:  # 生成未通过白名单校验的红色警告文案
    """未通过白名单校验时的红色提示语。"""
    return f"⚠️ 安全校验：回答中提到的「{'、'.join(drugs)}」未见于知识库原文，请勿据此自行购药或调整用量，务必由医生评估后决定。"  # 点名具体药名警示效力更强；引导就医而非自行用药

def banned_hits(answer: str, banned: list) -> list:  # 角色禁用术语检测（如心理医生讲了中医辨证）
    """回答里出现了该角色的禁用术语（如心理医生讲了中医辨证）。"""
    return [w for w in (banned or []) if w in answer]  # None 安全：banned 为空时按空列表处理，直接无命中
