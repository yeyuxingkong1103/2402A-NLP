# 招股说明书中大量使用「本公司」「发行人」「公司」等指代词，且出现于不同文件时指向不同主体。
# 抽取阶段按来源文件解析为对应发行人的全称，把指代词统一到同一实体，避免图谱出现孤立节点。
PRONOUN_ALIASES = ["本公司", "发行人", "公司", "本企业", "股份公司"]  # 需要按来源文件解析的指代词

_ORG_SUFFIX = ["股份有限公司", "有限责任公司", "有限公司", "集团股份有限公司", "公司"]  # 企业名称后缀（用于生成短名）


def normalize_name(name):                                       # 定义实体名归一化函数
    """去掉多余空白与书名号，把全角括号统一为半角，作为实体主键的基础形式。"""
    if not name:                                                # 空值直接返回空串
        return ""                                               # 返回空串
    s = str(name).strip()                                       # 去除首尾空白
    s = s.replace("（", "(").replace("）", ")")                   # 全角括号统一为半角
    s = s.replace("《", "").replace("》", "")                     # 去掉书名号（标准名中不携带）
    s = "".join(s.split())                                      # 去掉所有内部空白
    return s                                                    # 返回归一化后的名称


def short_name(name):                                           # 定义企业短名生成函数
    """把「武汉力源信息技术股份有限公司」映射为「武汉力源信息技术」，用于别名合并。"""
    s = normalize_name(name)                                    # 先做基础归一化
    for suf in _ORG_SUFFIX:                                     # 依次尝试剥离企业后缀
        if s.endswith(suf) and len(s) > len(suf):               # 名称长度必须大于后缀本身
            return s[:-len(suf)]                               # 返回去掉后缀的短名
    return s                                                    # 无可剥离后缀时返回原名


def build_extraction_prompt(chunks):                            # 定义抽取提示词构造函数
    """为一批语料块构造实体关系抽取提示词，约束实体类型与关系类型必须取自 schema。"""
    ent_lines = ["- %s：%s（示例：%s）" % (e["type"], e["desc"], e["examples"]) for e in ENTITY_TYPES]  # 渲染实体类型说明
    rel_lines = ["- %s：%s → %s，%s" % (r["relation"], r["head"], r["tail"], r["desc"]) for r in RELATION_TYPES]  # 渲染关系类型说明
    blocks = []                                                 # 初始化语料段落列表
    for c in chunks:                                            # 遍历本批语料块
        blocks.append("[块 %d | %s 第 %d 页]\n%s" % (c["id"], c["source"], c["page"], c["text"]))  # 渲染带来源标记的块
    system = ("你是招股说明书知识图谱抽取专家。请严格按给定 schema 从文本中抽取实体与关系，"
              "不得编造文本中不存在的信息。")                     # 系统提示：约束不得编造
    user = """可用的实体类型（必须且只能从下列类型中选取 type）：
%s

可用的关系类型（必须且只能从下列类型中选取 relation，并遵守头尾实体类型约束）：
%s

待抽取文本：
%s

抽取要求：
1. 实体 name 必须使用文本中出现的完整正式名称（企业用全称，不要简写）；文本中的「本公司」「发行人」请替换为该公司全称。
2. 只抽取有明确事实依据的实体与关系，不确定的不要输出。
3. 关系若带数值（持股比例、金额、收入等），填入 value 字段；若带报告期，填入 period 字段。
4. desc 用一句短语概括该实体或关系在文本中的关键信息（不超过 40 字）。
5. 实体去重：同一实体只输出一次，同一批文本内多次出现时合并描述。

只输出如下 JSON：
{"entities": [{"name": "实体名", "type": "实体类型", "desc": "描述"}],
 "relations": [{"head": "头实体名", "head_type": "类型", "relation": "关系类型",
                "tail": "尾实体名", "tail_type": "类型", "value": "数值或空", "period": "报告期或空", "desc": "描述"}]}"""  % (
        "\n".join(ent_lines), "\n".join(rel_lines), "\n\n".join(blocks))  # 填充类型说明与语料
    return system, user                                         # 返回系统提示与用户提示


